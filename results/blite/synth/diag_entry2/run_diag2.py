"""Entry capacity of the ``tko_in`` insertion settings on synthetic B-lite net4 (seed 1001).

Copy of ``results/blite/synth/diag_entry/run_diag.py`` (the A/B/C/D insertion diagnostic),
extended with the E/F/G departure-speed variants, the H/I capacity ramps and the weave
instrumentation.  Everything is written under ``results/blite/synth/diag_entry2/`` only; no
frozen file is touched.

Variants (all incident-free, 7,200 s, same G1-G3 evaluation as
``results/blite/synth/run_g123.py``):

* **E** ``departLane="free"``,  ``departSpeed="desired"``;
* **F** ``departLane="free"``,  ``departSpeed="last"``;
* **G** ``departLane="best"``,  ``departSpeed="desired"``;
* **H** capacity ramp 1,000 -> 4,000 veh/h at ``tko_in`` over 0-7,200 s (same 75/25 split,
  the four cross-street stubs unchanged), ``departLane="free"``, ``departSpeed="max"``;
* **I** same ramp with ``departSpeed="desired"``.

E/F/G are copies of ``scenarios/kwuntong/blite/synth/proxy.rou.xml`` with the two departure
attributes rewritten.  H/I are generated by rescaling the baseline ``tko_in`` departure
stream to the ramp rate lambda(t) = 1000 + 3000*t/7200 veh/h (inverse-CDF sampling of a
non-homogeneous Poisson process conditioned on the exact vehicle count, seed 1001, vehicle
classes kept in baseline depart order) so the route set and the 75/25 split are unchanged.

Extra instrumentation on top of ``diag_entry/run_diag.py``:

* per-lane 300 s E1 bins (all detectors, so the ``tko_in`` entry throughput can be read at
  the 5-min resolution the ramp analysis needs);
* per-minute mean speed and halting per lane on ``tko_in`` / ``tko_1`` / ``tko_vms`` /
  ``tko_a1`` (1-min resolution look at the weave);
* lane-change counts per edge on ``tko_1`` and ``tko_vms``;
* ``tko_a1`` lanes, so the minor movements ``tko_vms`` -> ``tko_a1`` (``state="m"`` at
  junction D) can be separated from the major ones.

Usage::

    python results/blite/synth/diag_entry2/run_diag2.py --build
    python results/blite/synth/diag_entry2/run_diag2.py --variant E
    python results/blite/synth/diag_entry2/run_diag2.py --summary
"""
