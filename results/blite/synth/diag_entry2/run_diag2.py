def ramp_rate(t):
    """Offered ``tko_in`` demand (veh/h) at time ``t`` (s) on the linear ramp."""
    return RAMP_VPH0 + (RAMP_VPH1 - RAMP_VPH0) * (float(t) / float(END))


def ramp_cumulative(t):
    """Vehicles offered at ``tko_in`` in [0, t] under the linear ramp."""
    a = (RAMP_VPH1 - RAMP_VPH0) / (2.0 * END)
    return (RAMP_VPH0 * t + a * t * t) / 3600.0


def ramp_inverse(u):
    """Time at which the ramp has offered ``u`` vehicles (inverse of ``ramp_cumulative``)."""
    a = (RAMP_VPH1 - RAMP_VPH0) / (2.0 * END)
    return (-RAMP_VPH0 + np.sqrt(RAMP_VPH0 ** 2 + 4.0 * a * u * 3600.0)) / (2.0 * a)


def _attr_sub(src, lane, speed):
    out = src.replace('departLane="best"', f'departLane="{lane}"')
    return out.replace('departSpeed="max"', f'departSpeed="{speed}"')


def build_variants():
    """Create the E/F/G route copies and the H/I ramp route files."""
    VAR.mkdir(parents=True, exist_ok=True)
    src = PROXY_ROU.read_text(encoding='utf-8')
    n = src.count('departLane="best"')
    for tag, lane, speed in (('E', 'free', 'desired'), ('F', 'free', 'last'),
                             ('G', 'best', 'desired')):
        out = VAR / f'proxy_{tag}.rou.xml'
        out.write_text(_attr_sub(src, lane, speed), encoding='utf-8')
        print(f'[build] {out} ({n} vehicles: departLane="{lane}", departSpeed="{speed}")')

    build_ramp('H', 'free', 'max')
    build_ramp('I', 'free', 'desired')


def build_ramp(tag, lane, speed):
    """Rescale the baseline ``tko_in`` departure stream to the linear ramp; stubs untouched."""
    root = ET.parse(PROXY_ROU).getroot()
    tko = []          # (depart, route edges) of the tko_in vehicles, in baseline depart order
    stub = []         # (depart, route edges) of the cross-street stub vehicles, unchanged
    for v in root.iter('vehicle'):
        edges = v.find('route').get('edges')
        if edges.split()[0] == 'tko_in':
            tko.append((float(v.get('depart')), edges))
        else:
            stub.append((float(v.get('depart')), edges))
    tko.sort(key=lambda x: x[0])
    n0 = len(tko)
    n = int(round(ramp_cumulative(END)))

    rng = np.random.default_rng(RAMP_SEED)
    u = np.arange(n, dtype=float) + rng.uniform(size=n)
    departs = ramp_inverse(u)
    classes = [tko[min(int(i * n0 // n), n0 - 1)][1] for i in range(n)]

    vehicles = list(zip(departs.tolist(), classes)) + stub
    vehicles.sort(key=lambda x: x[0])

    out_root = ET.Element('routes')
    for i, (dep, edges) in enumerate(vehicles):
        v = ET.SubElement(out_root, 'vehicle', id=f'p{i}', depart=f'{dep:.3f}', type='pdist',
                          departLane=lane, departSpeed=speed)
        ET.SubElement(v, 'route', edges=edges)
    out = VAR / f'ramp_{tag}.rou.xml'
    ET.indent(ET.ElementTree(out_root), space='  ')
    ET.ElementTree(out_root).write(out, encoding='utf-8', xml_declaration=True)

    meta = {
        'tag': tag,
        'departLane': lane,
        'departSpeed': speed,
        'vph_start': RAMP_VPH0,
        'vph_end': RAMP_VPH1,
        'horizon_s': END,
        'seed': RAMP_SEED,
        'baseline_tko_in_vehicles': n0,
        'ramp_tko_in_vehicles': n,
        'stub_vehicles': len(stub),
        'total_vehicles': len(vehicles),
        'first_depart': vehicles[0][0],
        'last_depart': vehicles[-1][0],
        'method': ('inverse-CDF sampling of a non-homogeneous Poisson process with linear '
                   'rate, conditioned on the exact vehicle count; vehicle classes kept in '
                   'baseline depart order; cross-street stub departures unchanged'),
        'bin_target_vph': {str(b): round(ramp_rate(b), 1) for b in range(0, END, BIN)},
    }
    (VAR / f'ramp_{tag}.json').write_text(json.dumps(meta, indent=2), encoding='utf-8')
    print(f'[build] {out} ({n0} baseline tko_in -> {n} ramp vehicles, '
          f'{len(stub)} stubs unchanged, depart {vehicles[0][0]:.1f}..{vehicles[-1][0]:.1f} s)')


def read_e1(path):
    """Read an E1 detector file: id -> [(begin, end, nVehContrib, nVehEntered), ...]."""
    out = defaultdict(list)
    for iv in ET.parse(path).getroot().iter('interval'):
        out[iv.get('id')].append((float(iv.get('begin')), float(iv.get('end')),
                                  int(iv.get('nVehContrib')), int(iv.get('nVehEntered'))))
    return out


def write_dets(run_dir):
    """E1 loops with a 300 s period.

    The flows are read from the detector's own interval file, never from
    ``inductionloop.getLastStepVehicleNumber``: that call reports a vehicle on *two*
    consecutive steps (one on entering and one on leaving the loop area), so accumulating it
    per step roughly doubles every count (probe: ``probe_det.py`` / ``probe_micro``).
    """
    root = ET.Element('additional')
    for did, lane, pos in DET_LANES:
        ET.SubElement(root, 'inductionLoop', {
            'id': did, 'lane': lane, 'pos': str(pos), 'period': str(BIN),
            'file': str(run_dir / 'e1diag.xml')})
    ET.indent(ET.ElementTree(root), space='    ')
    path = run_dir / 'diag_dets.add.xml'
    ET.ElementTree(root).write(path, encoding='utf-8', xml_declaration=True)
    return path


def sumo_cmd(run_dir, seed, routes, net, det_file):
    cmd = [
        sumo_bin('sumo'),
        '-n', str(net),
        '-a', f'{VTYPES_PROXY},{det_file},{TLS_WEBSTER}',
        '-r', str(routes),
        '--seed', str(seed),
        '--step-length', '1',
        '--no-step-log', 'true',
        '--no-warnings', 'true',
        '--time-to-teleport', '-1',
        '--collision.action', 'warn',
        '--collision-output', str(run_dir / 'collisions.xml'),
        '--end', str(END),
        '--error-log', str(run_dir / 'sumo.log'),
    ]
    if G.reroute_enabled():
        cmd += ['--device.rerouting.probability', '0.3', '--device.rerouting.period', '60']
    return cmd


def run_variant(tag, routes=None, net=None, seed=SEED):
    import libsumo as tc

    routes = Path(routes or VARIANTS[tag]['routes'])
    net = Path(net or VARIANTS[tag]['net'])
    run_dir = DIAG / tag
    if run_dir.exists():
        shutil.rmtree(run_dir)
    run_dir.mkdir(parents=True, exist_ok=True)

    vehicles = {}
    for v in ET.parse(routes).getroot().iter('vehicle'):
        vehicles[v.get('id')] = (v.find('route').get('edges').split()[0], float(v.get('depart')))
    departures = sorted(d for _, d in vehicles.values())
    sources = sorted({src for src, _ in vehicles.values()})

    det_file = write_dets(run_dir)
    cmd = sumo_cmd(run_dir, seed, routes, net, det_file)
    print(' '.join(cmd), flush=True)

    teleports = 0
    arrived = 0
    out_reached = set()
    history = []
    backlog = defaultdict(dict)
    total_pending = {}
    lane_flow = Counter()          # detector id -> vehicles in the last hour
    lane_flow_full = Counter()     # detector id -> vehicles over the whole run
    lane_entries = Counter()       # lane id -> vehicle entries in the last hour (cross-check)
    seen_on_lane = {}
    halt_sum = Counter()
    halt_peak = Counter()
    halt_steps = 0
    departed_bins = defaultdict(Counter)   # bin start -> source -> insertions in the bin
    departed_total = Counter()             # source -> insertions over the whole run
    speed_bins = defaultdict(Counter)   # bin start -> lane -> vehicle-seconds
    speed_veh = defaultdict(Counter)    # bin start -> lane -> vehicle count
    minute_speed = []
    minute_halt = []
    lane_change = Counter()
    prev_lane = {}
    flush_arrivals = None
    pre_flush_running = None

    started = time.monotonic()
    tc.start(cmd)
    try:
        init_signals(tc)
        for k in range(1, END + 1):
            tc.simulationStep()
            teleports += int(tc.simulation.getStartingTeleportNumber())
            teleports += int(tc.simulation.getEndingTeleportNumber())
            arrived += int(tc.simulation.getArrivedNumber())
            for vid in tc.edge.getLastStepVehicleIDs('out'):
                out_reached.add(vid)

            # Exact insertion counts per source (SUMO's own departed list).
            for vid in tc.simulation.getDepartedIDList():
                src = vehicles.get(vid, ('?',))[0]
                departed_bins[(k - 1) // BIN * BIN][src] += 1
                departed_total[src] += 1

            for did, lane, _ in DET_LANES:
                cur = set(tc.lane.getLastStepVehicleIDs(lane))
                prev = seen_on_lane.get(lane, set())
                if k > END - LAST_HOUR:
                    lane_entries[lane] += len(cur - prev)
                seen_on_lane[lane] = cur

            b = (k - 1) // BIN * BIN
            for lane in SPEED_LANES:
                nv = int(tc.lane.getLastStepVehicleNumber(lane))
                if nv:
                    speed_bins[b][lane] += float(tc.lane.getLastStepMeanSpeed(lane)) * nv
                    speed_veh[b][lane] += nv

            for eid in WEAVE_EDGES:
                for vid in tc.edge.getLastStepVehicleIDs(eid):
                    lane = tc.vehicle.getLaneID(vid)
                    p = prev_lane.get(vid)
                    if p is not None and p != lane and p.startswith(eid + '_'):
                        lane_change[eid] += 1
                    prev_lane[vid] = lane

            if k > END - LAST30:
                halt_steps += 1
                for eid in HALT_EDGES:
                    h = int(tc.edge.getLastStepHaltingNumber(eid))
                    halt_sum[eid] += h
                    if h > halt_peak[eid]:
                        halt_peak[eid] = h

            if k % 60 == 0:
                minute_speed.append({
                    'time': k,
                    **{lane: round(float(tc.lane.getLastStepMeanSpeed(lane)), 3)
                       for lane in SPEED_LANES}})
                minute_halt.append({
                    'time': k,
                    **{lane: int(tc.lane.getLastStepHaltingNumber(lane))
                       for lane in SPEED_LANES}})
                pending_vids = list(tc.simulation.getPendingVehicles())
                by_source = Counter(vehicles[vid][0] for vid in pending_vids if vid in vehicles)
                for src in sources:
                    backlog[src][k] = by_source.get(src, 0)
                total_pending[k] = len(pending_vids)
                history.append({
                    'time': k,
                    'scheduled_due': int(np.searchsorted(departures, k, side='left')),
                    'running': int(tc.vehicle.getIDCount()),
                    'pending_total': len(pending_vids),
                    **{f'pending_{src}': by_source.get(src, 0) for src in sources},
                    'arrived': arrived,
                    'discharge_out': len(out_reached),
                })
                if k == END:
                    pre_flush_running = int(tc.vehicle.getIDCount())

        # Mirrors run_g123: one extra step so departures at the horizon are registered.
        tc.simulationStep()
        arrived += int(tc.simulation.getArrivedNumber())
        teleports += int(tc.simulation.getStartingTeleportNumber())
        teleports += int(tc.simulation.getEndingTeleportNumber())
        end_running = int(tc.vehicle.getIDCount())
        end_pending = len(list(tc.simulation.getPendingVehicles()))
        collisions = len(list(tc.simulation.getCollisions()))
        flush_arrivals = arrived - history[-1]['arrived']
    finally:
        tc.close()
    wall = time.monotonic() - started

    e1 = read_e1(run_dir / 'e1diag.xml')   # exact 300 s flows per detector

    with (run_dir / 'history.csv').open('w', newline='', encoding='utf-8') as fh:
        writer = csv.DictWriter(fh, fieldnames=list(history[0].keys()))
        writer.writeheader()
        writer.writerows(history)
    with (run_dir / 'pending_by_source.csv').open('w', newline='', encoding='utf-8') as fh:
        writer = csv.writer(fh)
        writer.writerow(['time', 'source', 'pending'])
        for src in sources:
            for t in sorted(backlog[src]):
                writer.writerow([t, src, backlog[src][t]])
    with (run_dir / 'speed_per_min.csv').open('w', newline='', encoding='utf-8') as fh:
        writer = csv.DictWriter(fh, fieldnames=list(minute_speed[0].keys()))
        writer.writeheader()
        writer.writerows(minute_speed)
    with (run_dir / 'halt_per_min.csv').open('w', newline='', encoding='utf-8') as fh:
        writer = csv.DictWriter(fh, fieldnames=list(minute_halt[0].keys()))
        writer.writeheader()
        writer.writerows(minute_halt)
    with (run_dir / 'bins300.csv').open('w', newline='', encoding='utf-8') as fh:
        writer = csv.writer(fh)
        writer.writerow(['t0', 't1', 'detector', 'lane', 'n', 'vph', 'n_entered', 'inserted'])
        for b in range(0, END, BIN):
            for did, lane, _ in DET_LANES:
                iv = next((x for x in e1.get(did, []) if x[0] == b and x[1] <= END), None)
                n = iv[2] if iv else 0
                ent = iv[3] if iv else 0
                ins = sum(departed_bins[b].values()) if did == 'dk_tko_in_0' else ''
                writer.writerow([b, b + BIN, did, lane, n, round(n * 3600.0 / BIN, 1), ent, ins])
    with (run_dir / 'insertions300.csv').open('w', newline='', encoding='utf-8') as fh:
        writer = csv.writer(fh)
        writer.writerow(['t0', 't1', 'source', 'inserted', 'vph'])
        for b in range(0, END, BIN):
            for src in sources:
                n = departed_bins[b][src]
                writer.writerow([b, b + BIN, src, n, round(n * 3600.0 / BIN, 1)])
    with (run_dir / 'speed_bins300.csv').open('w', newline='', encoding='utf-8') as fh:
        writer = csv.writer(fh)
        writer.writerow(['t0', 't1', 'lane', 'mean_speed_ms', 'veh_steps'])
        for b in sorted(speed_bins):
            for lane in SPEED_LANES:
                nv = speed_veh[b][lane]
                sp = (speed_bins[b][lane] / nv) if nv else float('nan')
                writer.writerow([b, b + BIN, lane, round(sp, 3), nv])

    scheduled_end = int(np.searchsorted(departures, END, side='left'))
    conservation_gap = scheduled_end - (end_pending + end_running + arrived)
    pending_share = end_pending / max(scheduled_end, 1)
    running_windows = G.window_slopes({h['time']: h['running'] for h in history})
    backlog_windows = {src: G.window_slopes(backlog[src]) for src in sources}
    g1_pass = (teleports == 0 and collisions == 0)
    g2_pass = (conservation_gap == 0)
    g3_pass = bool(
        pending_share <= G.PENDING_SHARE_LIMIT
        and all(w['pass'] for w in running_windows)
        and all(w['pass'] for rows in backlog_windows.values() for w in rows)
    )

    per_lane = {}
    for did, lane, _ in DET_LANES:
        ivs = [iv for iv in e1.get(did, []) if iv[1] <= END]
        last_hour = sum(iv[2] for iv in ivs if iv[0] >= END - LAST_HOUR)
        per_lane[did] = {
            'lane': lane,
            'last_hour': last_hour,
            'last_hour_vph': last_hour * 3600.0 / LAST_HOUR,
            'full_run': sum(iv[2] for iv in ivs),
            'bins300': [{'t0': iv[0], 't1': iv[1], 'n': iv[2], 'entered': iv[3]} for iv in ivs],
            'lane_entries_last_hour': lane_entries[lane],
        }
    halting = {e: {'mean_last30': round(halt_sum[e] / max(halt_steps, 1), 3),
                   'max_last30': int(halt_peak[e])} for e in HALT_EDGES}

    # 5-min tko_in throughput series (E1 intervals) and the best 3-consecutive-bin plateau.
    in_dets = [d for d, lane, _ in DET_LANES if lane.startswith('tko_in_')]
    series = []
    for b in range(WARMUP, END, BIN):
        n = sum(iv['n'] for d in in_dets for iv in per_lane[d]['bins300'] if iv['t0'] == b)
        ins = departed_bins[b]['tko_in']
        series.append({'t0': b, 't1': b + BIN, 'n': n, 'vph': n * 3600.0 / BIN,
                       'inserted': ins, 'inserted_vph': ins * 3600.0 / BIN,
                       'demand_vph': round(ramp_rate(b + BIN / 2.0), 1)
                       if VARIANTS[tag]['ramp'] else None})
    plateau = None
    for i in range(len(series) - 2):
        window = series[i:i + 3]
        vph = sum(w['n'] for w in window) * 3600.0 / (3 * BIN)
        if plateau is None or vph > plateau['vph']:
            plateau = {'t0': window[0]['t0'], 't1': window[-1]['t1'],
                       'vph': vph, 'veh': sum(w['n'] for w in window),
                       'bins': [w['t0'] for w in window]}
    plateau_ins = None
    for i in range(len(series) - 2):
        window = series[i:i + 3]
        vph = sum(w['inserted'] for w in window) * 3600.0 / (3 * BIN)
        if plateau_ins is None or vph > plateau_ins['vph']:
            plateau_ins = {'t0': window[0]['t0'], 't1': window[-1]['t1'],
                           'vph': vph, 'veh': sum(w['inserted'] for w in window),
                           'bins': [w['t0'] for w in window]}

    pending_in = backlog.get('tko_in', {})
    onset = None
    for t in sorted(pending_in):
        if pending_in[t] > 50:
            onset = {'time': t, 'pending': pending_in[t],
                     'demand_vph': round(ramp_rate(t), 1),
                     'bin_vph': next((w['vph'] for w in series if w['t0'] <= t - 1 < w['t1']),
                                     None)}
            break
    onset40 = None
    for t in sorted(pending_in):
        if pending_in[t] > 20:
            onset40 = {'time': t, 'pending': pending_in[t], 'demand_vph': round(ramp_rate(t), 1)}
            break

    meta = {
        'tag': tag,
        'seed': seed,
        'change': VARIANTS[tag]['change'],
        'ramp': VARIANTS[tag]['ramp'],
        'routes': str(routes),
        'net': str(net),
        'wall_seconds': round(wall, 2),
        'loaded_vehicles': len(vehicles),
        'scheduled_departures': scheduled_end,
        'pre_flush_running': pre_flush_running,
        'running_end': end_running,
        'pending_end': end_pending,
        'pending_end_tko_in': pending_in.get(END, 0),
        'arrived_end': arrived,
        'flush_arrivals': flush_arrivals,
        'out_end': len(out_reached),
        'discharge_out_vph': len(out_reached) / (END / 3600.0),
        'conservation_gap': conservation_gap,
        'teleports': int(teleports),
        'collisions': int(collisions),
        'pending_share': pending_share,
        'g1_pass': bool(g1_pass),
        'g2_pass': bool(g2_pass),
        'g3_pass': bool(g3_pass),
        'all_gates_pass': bool(g1_pass and g2_pass and g3_pass),
        'backlog_windows_tko_in': backlog_windows.get('tko_in', []),
        'running_windows': running_windows,
        'per_lane': per_lane,
        'halting': halting,
        'sources': sources,
        'bins300_tko_in': series,
        'entry_capacity_plateau': plateau,
        'entry_capacity_plateau_inserted': plateau_ins,
        'insertions_by_source': {s: int(departed_total[s]) for s in sources},
        'backlog_onset_50': onset,
        'backlog_onset_20': onset40,
        'lane_changes': {e: int(lane_change[e]) for e in WEAVE_EDGES},
        'max_pending_tko_in': max(pending_in.values()) if pending_in else 0,
        'peak_pending_time': max(pending_in, key=lambda t: pending_in[t]) if pending_in else 0,
    }
    (run_dir / 'run.json').write_text(json.dumps(meta, indent=2), encoding='utf-8')
    print(json.dumps({k: meta[k] for k in (
        'tag', 'scheduled_departures', 'pending_end', 'running_end', 'arrived_end',
        'conservation_gap', 'teleports', 'collisions', 'g1_pass', 'g2_pass', 'g3_pass',
        'discharge_out_vph')}, indent=2), flush=True)
    if plateau:
        print('entry capacity plateau (E1):', json.dumps(plateau), flush=True)
    if plateau_ins:
        print('entry capacity plateau (insertions):', json.dumps(plateau_ins), flush=True)
    if onset:
        print('backlog > 50 veh at:', json.dumps(onset), flush=True)
    print('lane changes:', meta['lane_changes'], flush=True)
    return meta


def summary(tags=('E', 'F', 'G', 'H', 'I')):
    rows = []
    for tag in tags:
        p = DIAG / tag / 'run.json'
        if not p.exists():
            print(f'[summary] missing {p}')
            continue
        rows.append(json.loads(p.read_text(encoding='utf-8')))
    return rows


def main(argv=None):
    ap = argparse.ArgumentParser(description='tko_in entry-capacity diagnostics (E/F/G/H/I).')
    ap.add_argument('--build', action='store_true')
    ap.add_argument('--variant')
    ap.add_argument('--summary', action='store_true')
    args = ap.parse_args(argv)

    os.environ.setdefault('CITYPULSE_NET', 'blite')
    os.environ.setdefault('CITYPULSE_BLITE_REV', '4')
    os.environ.setdefault('CITYPULSE_REROUTE', '0')

    if args.build:
        build_variants()
    if args.variant:
        run_variant(args.variant)
    if args.summary:
        for m in summary():
            print(json.dumps(m, indent=2))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
